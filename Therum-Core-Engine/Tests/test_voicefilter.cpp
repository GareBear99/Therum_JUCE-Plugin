// test_voicefilter — the Moog ladder wired into the Therum voice.
//
// Paper section 4.5, rank 7 (ladder) and section 7 (filter response
// test): the ladder is a selectable filter type in the voice
// (VoiceFilter), alongside the SVF, running at 1x in production
// (Gary's call, 2026-11-05). The 2x build stays built and measured;
// it is measurement mode only for the voice path.
//
// Expected behaviour (defined BEFORE the tests were run):
//   (E1) Ladder equivalence: the VoiceFilter in Ladder mode produces
//        the same output, sample for sample, as a standalone
//        MoogLadderFilter at 1x with the same cutoff/resonance —
//        the wiring adds no gain, no offset, no extra stage.
//        Hand-checkable case: 440 Hz sine, amp 0.5, fc = 1000 Hz,
//        reso = 0, 1 s: max|diff| < 1e-6 (same code, same inputs).
//   (E2) SVF path unchanged: the VoiceFilter in SVF mode produces
//        the same output as a standalone SvfFilter with the same
//        type/cutoff/Q/drive — the wiring did not touch the
//        shipped voice filter. Same tolerance, all four SVF types.
//   (E3) Ladder cutoff clamp: at 1x the ladder's cutoff is clamped
//        to 20 Hz .. sr/(2*pi) (alpha <= 1), so it stays a lowpass.
//        At 44.1 kHz that is ~7018 Hz; at 48 kHz ~7639 Hz. The SVF
//        keeps its own 20 Hz .. min(20 kHz, Nyquist) clamp.
//   (E4) Type switching (SVF <-> ladder) is click-free: a 128-sample
//        crossfade blends the engines, so the largest per-sample
//        step during a switch is at most 2x the largest step in
//        steady state; after the crossfade the output matches the
//        single-engine reference (RMS diff < 1e-3); no DC offset
//        (|mean| < 0.005 on a zero-mean sine) and no NaN anywhere.
//   (E5) Denormals: after a decaying input and 2 s of zeros, the
//        output is exactly 0.0 (not a denormal), both engines.
//   (E6) Stability at 1x: fc x reso sweep (fc = 20/100/1000/4000/
//        7000 Hz, reso = 0/0.5/0.9/1.0), sine + impulse, 1 s each:
//        every combination finite, max|out| < 4.0. Self-oscillation
//        (reso = 1.0, fc = 1000 Hz): sustained (RMS > 0.05 in the
//        last 0.5 s), bounded (max|out| < 2.0), pitch within 15%
//        of fc. The pitch droops with the Euler warping of the loop
//        phase, and the droop scales with alpha = 2*pi*fc/fs_os
//        (measured on the standalone ladder: 94.0% of fc at
//        alpha = 0.071, 89.2% at alpha = 0.1425, 82.5% at
//        alpha = 0.285) — at 1x the rate is halved, so the droop
//        doubles vs 2x, and the bound is set from that scaling,
//        not copied from the 2x test. At fc = 7000 Hz (alpha = 1)
//        the pitch is report-only.
//   (E7) Voice render: the VoiceManager path renders through the
//        ladder (finite, bounded, audibly different from the SVF
//        at the same cutoff/reso — the ladder actually engages),
//        and a mid-note type switch stays finite and bounded.
//   (E8) NMR renders: six WAVs for the Bench nmr_test.py
//        (aliases judged against the masking curve, not a bare dB
//        number). The SINE renders are the ladder-alias verdict:
//        a 5 kHz sine has one harmonic, so every other peak is
//        generated by the ladder's tanh — the NMR test judges
//        exactly the ladder's folded products. The saw renders
//        (voice, direct 1x/2x, dry) are reported for completeness
//        but are NOT the verdict: the dry saw alone "fails" NMR
//        on a 349.9 Hz oscillator artefact, and the voice render
//        on its detuned 3rd harmonic — the classifier cannot tell
//        oscillator content from ladder aliases there. Run it by
//        hand afterwards:
//          python3 ~/workspace/ARC-AudioBench/scripts/nmr_test.py \
//              --f0 5000 voicefilter_sine_ladder_1x.wav
//
// Build and run: `make voicefilter` (see Makefile), or:
//   g++ -std=c++17 -O2 -Wall -Wextra -o test_voicefilter \
//       test_voicefilter.cpp \
//       ../Source/DSP/Filters/MoogLadderFilter.cpp \
//       ../Source/DSP/Filters/SvfFilter.cpp \
//       ../Source/DSP/Oscillators/WavetableOscillator.cpp \
//       ../Source/DSP/Oscillators/WavetableBank.cpp \
//       ../Source/DSP/Oscillators/WavetableBankMips.cpp \
//       ../Source/DSP/Utils/Fft.cpp \
//       ../Source/DSP/Utils/WavImport.cpp \
//       ../Source/DSP/Modulation/EnvelopeGenerator.cpp \
//       ../Source/DSP/Voicing/TherumVoice.cpp \
//       ../Source/DSP/Voicing/VoiceManager.cpp \
//       ../Source/DSP/FX/FxRack.cpp
//   ./test_voicefilter
// Exit code 0 means every check passed; non-zero means a check
// failed (failures are printed with file and line).

